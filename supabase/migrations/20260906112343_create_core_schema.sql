-- ============================================================
-- INDEXES
-- ============================================================

-- Cases: frequently filtered by status and risk_level
CREATE INDEX IF NOT EXISTS idx_cases_status ON cases(status);
CREATE INDEX IF NOT EXISTS idx_cases_risk_level ON cases(risk_level);
CREATE INDEX IF NOT EXISTS idx_cases_created_by ON cases(created_by);
CREATE INDEX IF NOT EXISTS idx_cases_created_at ON cases(created_at DESC);

-- Evidence: list by case
CREATE INDEX IF NOT EXISTS idx_evidence_case_id ON evidence(case_id);
CREATE INDEX IF NOT EXISTS idx_evidence_uploaded_at ON evidence(uploaded_at DESC);

-- Events: timeline queries (case + timestamp is the most common query)
CREATE INDEX IF NOT EXISTS idx_events_case_timestamp ON events(case_id, timestamp);
CREATE INDEX IF NOT EXISTS idx_events_case_type ON events(case_id, event_type);
CREATE INDEX IF NOT EXISTS idx_events_case_source_ip ON events(case_id, source_ip);
CREATE INDEX IF NOT EXISTS idx_events_case_severity ON events(case_id, severity);
CREATE INDEX IF NOT EXISTS idx_events_evidence_id ON events(evidence_id);

-- Alerts: sorted by severity and creation time
CREATE INDEX IF NOT EXISTS idx_alerts_case_severity ON alerts(case_id, severity);
CREATE INDEX IF NOT EXISTS idx_alerts_case_created_at ON alerts(case_id, created_at DESC);

-- Indicators: sorted by occurrence count
CREATE INDEX IF NOT EXISTS idx_indicators_case_id ON indicators(case_id);
CREATE INDEX IF NOT EXISTS idx_indicators_type_value ON indicators(type, value);

-- Audit logs: user activity history
CREATE INDEX IF NOT EXISTS idx_audit_logs_user_id ON audit_logs(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_logs_timestamp ON audit_logs(timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action ON audit_logs(action);

-- ============================================================
-- UPDATED_AT TRIGGER FOR CASES
-- ============================================================
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS cases_updated_at ON cases;
CREATE TRIGGER cases_updated_at
  BEFORE UPDATE ON cases
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();
