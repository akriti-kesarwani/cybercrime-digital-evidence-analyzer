/*
# Create Core Database Schema for Cybercrime Digital Evidence Analyzer

## Overview
This migration creates the complete database schema for a digital forensics
investigation platform. It includes 7 core tables plus a profiles table
linked to Supabase auth, with full relationships, constraints, indexes,
and Row-Level Security policies.

## New Tables

1. **profiles** — Extended user data linked to auth.users. Stores name and role
   (ADMIN, INVESTIGATOR, VIEWER). Auto-created via trigger on signup.

2. **cases** — Investigation cases. Each case has a unique case number
   (CASE-YYYY-NNN), name, description, status, and risk level.

3. **evidence** — Uploaded evidence files. Stores filename, file type, size,
   SHA-256 hash, storage path, and integrity status.

4. **events** — Normalized events extracted from evidence. Each event has a
   timestamp, type, username, source/destination IP, severity, and raw data.

5. **alerts** — Generated by the detection engine. Each alert references a
   case and has a type, severity, confidence score, reason, and detection rule.

6. **indicators** — Extracted indicators of compromise (IPs, usernames,
   filenames, domains, URLs, hashes) with occurrence counts and risk scores.

7. **audit_logs** — Records all significant user actions for chain of custody.

## Security
- RLS enabled on ALL tables
- Owner-scoped policies using auth.uid() for cases, evidence, events, alerts,
  indicators, and audit_logs
- Profiles are readable by the owner and writable by the owner (except role,
  which is only set at creation)
- All policies use TO authenticated with proper ownership checks

## Important Notes
1. The profiles table is auto-populated by a trigger when a new auth user is created.
2. The role is stored in raw_user_meta_data at signup and copied to profiles.
3. Case numbers are generated by the application as CASE-YYYY-NNN format.
4. Evidence SHA-256 hashes are computed client-side using the Web Crypto API.
5. All foreign keys use ON DELETE CASCADE to maintain referential integrity.
*/

-- ============================================================
-- PROFILES TABLE
-- ============================================================
CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL DEFAULT '',
  email text NOT NULL,
  role text NOT NULL DEFAULT 'VIEWER' CHECK (role IN ('ADMIN', 'INVESTIGATOR', 'VIEWER')),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;

-- Profiles: users can read their own profile
DROP POLICY IF EXISTS "select_own_profile" ON profiles;
CREATE POLICY "select_own_profile" ON profiles FOR SELECT
  TO authenticated USING (auth.uid() = id);

-- Profiles: users can update their own profile (name only, not role)
DROP POLICY IF EXISTS "update_own_profile" ON profiles;
CREATE POLICY "update_own_profile" ON profiles FOR UPDATE
  TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

-- Profiles: admins can read all profiles (for user management)
DROP POLICY IF EXISTS "admin_select_all_profiles" ON profiles;
CREATE POLICY "admin_select_all_profiles" ON profiles FOR SELECT
  TO authenticated USING (
    EXISTS (SELECT 1 FROM profiles p WHERE p.id = auth.uid() AND p.role = 'ADMIN')
  );

-- ============================================================
-- AUTO-CREATE PROFILE ON SIGNUP
-- Trigger function that creates a profiles row when a new auth.users row is inserted.
-- The role is read from raw_user_meta_data (set during signUp).
-- ============================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, email, name, role)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'name', ''),
    COALESCE(NEW.raw_user_meta_data->>'role', 'INVESTIGATOR')
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

